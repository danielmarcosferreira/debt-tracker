const dictionaries: Record<LanguageCode, Record<TranslationKey, string>> = {
  en,
  pt,
};

function interpolate(template: string, vars?: Record<string, string | number>) {
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (match, key) =>
    key in vars ? String(vars[key]) : match
  );
}

export function translate(
  language: LanguageCode,
  key: TranslationKey,
  vars?: Record<string, string | number>
): string {
  const template = dictionaries[language]?.[key] ?? dictionaries.en[key] ?? key;
  return interpolate(template, vars);
}

/** Picks the `_one`/`_other` variant of a key based on count (English/Portuguese share this rule). */
export function translatePlural(
  language: LanguageCode,
  base: string,
  count: number,
  vars?: Record<string, string | number>
): string {
  const suffix = count === 1 ? "_one" : "_other";
  const key = `${base}${suffix}` as TranslationKey;
  return translate(language, key, { count, ...vars });
}

export function categoryLabel(language: LanguageCode, category: Category): string {
  return translate(language, `category.${category}` as TranslationKey);
}
